"""Regenerate the README's run-evidence assets from the committed demo journal.

Everything comes from docs/examples/samo71.jsonl.gz alone — no live quest, no
archive lookup, no network, no agent. The narrative and the ledger replay through
imp's own terminal renderers (render_tree / render_summary at color=False,
width=80), so a committed block is exactly what `imp log samo71` printed.

Run from the repo root, or via `make docs-assets`:

    .venv/bin/python scripts/gen_docs_assets.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))  # import the sibling scene modules by name

import capture_imp_ui as cap  # noqa: E402

from imp.cli import narrative as nv  # noqa: E402
from imp.cli.render_summary import (  # noqa: E402
    SummaryHeader,
    build_summary,
    render_summary,
    summary_total,
)
from imp.cli.render_text import render_tree  # noqa: E402

_REPO = _HERE.parent
DOCS = _REPO / "docs"
HERO_PNG = DOCS / "images" / "hero-run.png"
README = _REPO / "README.md"

QUEST = "samo71"
WIDTH = 80

# Ordinal ranges over the frozen journal — the excerpt's beats: the opening
# intent, imp's read-back of the design, the human's confirmation, the
# twelve-criteria walk, finalize's close, and the merge.
EXCERPT_RANGES = ((1, 3), (283, 286), (2684, 2684), (3144, 3156))

# What this run's own `imp log --summary` header printed; the journal carries neither.
WORKFLOW = "default"
STATUS = "merged"

# Line ranges over the 85-line ledger render: the threshold block, the spec
# block's two review rounds, one whole plan+implement cycle, the converge and
# integrate tail, and the total.
LEDGER_RANGES = ((0, 3), (8, 29), (63, 67), (73, 83))


def demo_events() -> list[dict[str, Any]]:
    return cap.journal_events(cap.DEMO_JOURNAL)


def _elision(count: int, unit: str) -> str:
    return f"  … {count:,} {unit} elided …"


def _fenced(command: str, lines: list[str]) -> str:
    return "\n".join(["```console", f"$ {command}", *lines, "```"]) + "\n"


def narrative_lines(events: list[dict[str, Any]],
                    ordinals: tuple[int, int] | None = None) -> list[str]:
    """The journal, or one ordinal range of it, through imp's narrative renderer.
    quest_created leads every slice: it renders nothing but names the quest,
    without which a tail slice closes on a bare `Merged  into master.`"""
    selected = [e for e in events if e["ordinal"] != 1
                and (ordinals is None
                     or ordinals[0] <= e["ordinal"] <= ordinals[1])]
    return list(render_tree(nv.build_tree([events[0], *selected]),
                            color=False, width=WIDTH))


def excerpt_text(events: list[dict[str, Any]]) -> str:
    lines: list[str] = []
    previous = 0
    for first, last in EXCERPT_RANGES:
        if previous:
            lines += ["", _elision(first - previous - 1, "events"), ""]
        lines += narrative_lines(events, (first, last))
        previous = last
    return _fenced(f"imp log {QUEST}", lines)


def ledger_lines(events: list[dict[str, Any]]) -> list[str]:
    header = SummaryHeader(workflow=WORKFLOW, quest_id=QUEST, status=STATUS,
                           total_seconds=summary_total(events))
    return render_summary(build_summary(events), header=header,
                          color=False, width=WIDTH)


def ledger_text(events: list[dict[str, Any]]) -> str:
    """An elided cut of the RENDERED ledger. Dropping StepRows before the render
    would recompute the total off the survivors and understate the run's cost;
    it would also drop the trailing list-price legend, which sits after the
    total row that closes this block."""
    full = ledger_lines(events)
    lines: list[str] = []
    previous = -1
    for first, last in LEDGER_RANGES:
        if previous >= 0:
            lines.append(_elision(first - previous - 1, "rows"))
        lines += full[first:last + 1]
        previous = last
    return _fenced(f"imp log {QUEST} --summary", lines)


def transcript_text(events: list[dict[str, Any]]) -> str:
    return (f"# {QUEST} — the complete run\n\n"
            f"Generated by `make docs-assets` from `docs/examples/{QUEST}.jsonl.gz`.\n"
            "Edits here are overwritten; change the generator instead.\n\n"
            + _fenced(f"imp log {QUEST}", narrative_lines(events)))


def check_width(name: str, text: str) -> None:
    over = [line for line in text.splitlines() if len(line) > WIDTH]
    if over:
        raise SystemExit(f"{name}: {len(over)} line(s) over {WIDTH} columns:\n"
                         + "\n".join(f"  {len(line)}: {line}" for line in over))


def text_assets(events: list[dict[str, Any]]) -> dict[str, str]:
    """Path under docs/ -> file text; the two README-bound blocks are width-checked
    on the way out, the linked full transcript deliberately is not."""
    excerpt, ledger = excerpt_text(events), ledger_text(events)
    check_width(f"{QUEST}-excerpt.md", excerpt)
    check_width(f"{QUEST}-ledger.md", ledger)
    return {f"examples/{QUEST}.md": transcript_text(events),
            f"examples/{QUEST}-excerpt.md": excerpt,
            f"examples/{QUEST}-ledger.md": ledger}


def write_text_assets(events: list[dict[str, Any]],
                      docs: Path = DOCS) -> list[Path]:
    written: list[Path] = []
    for relpath, text in text_assets(events).items():
        path = docs / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def splice_block(text: str, name: str, block: str) -> str:
    """HTML comments do not render on GitHub."""
    opener, closer = f"<!-- docs-assets:{name} -->\n", f"<!-- /docs-assets:{name} -->"
    head, opened, rest = text.partition(opener)
    _stale, closed, tail = rest.partition(closer)
    if not (opened and closed):
        raise SystemExit(f"README.md: no {opener.strip()} … {closer} pair to splice into")
    return head + opener + block + closer + tail


def splice_readme(events: list[dict[str, Any]], readme: Path = README) -> Path:
    """Both blocks come from text_assets, so a block that failed the width guard
    cannot reach the README."""
    assets = text_assets(events)
    text = readme.read_text(encoding="utf-8")
    for name in ("excerpt", "ledger"):
        text = splice_block(text, name, assets[f"examples/{QUEST}-{name}.md"])
    readme.write_text(text, encoding="utf-8")
    return readme


def render_hero_png(out: Path = HERO_PNG) -> Path:
    import snap_imp_ui as snap

    out.parent.mkdir(parents=True, exist_ok=True)
    snap.snap_stream_live(out, limit=cap.HERO_LIMIT, cols=cap.HERO_WIDTH,
                          rows=snap.HERO_ROWS)
    return out


def main() -> int:
    events = demo_events()
    for path in [*write_text_assets(events), render_hero_png()]:
        print(f"wrote {path.relative_to(_REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
