"""Regenerate the README's run-evidence assets from the committed demo journal.

Everything comes from docs/examples/samo71.jsonl.gz alone — no live quest, no
archive lookup, no network, no agent. The narrative and the ledger replay through
imp's own terminal renderers (render_tree / render_summary at color=False,
width=80), so a committed block is exactly what `imp log samo71` printed.

Run from the repo root, or via `make docs-assets`:

    .venv/bin/python scripts/gen_docs_assets.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))  # import the sibling scene modules by name

import capture_imp_ui as cap  # noqa: E402

from imp.cli import narrative as nv  # noqa: E402
from imp.cli.render_text import render_tree  # noqa: E402

_REPO = _HERE.parent
DOCS = _REPO / "docs"

QUEST = "samo71"
WIDTH = 80

# Ordinal ranges over the frozen journal — the excerpt's beats: the opening
# intent, imp's read-back of the design, the human's confirmation, the
# twelve-criteria walk, finalize's close, and the merge.
EXCERPT_RANGES = ((1, 3), (283, 286), (2684, 2684), (3144, 3156))


def demo_events() -> list[dict[str, Any]]:
    return cap.journal_events(cap.DEMO_JOURNAL)


def _elision(count: int, unit: str) -> str:
    return f"  … {count:,} {unit} elided …"


def _fenced(command: str, lines: list[str]) -> str:
    return "\n".join(["```console", f"$ {command}", *lines, "```"]) + "\n"


def narrative_lines(events: list[dict[str, Any]],
                    ordinals: tuple[int, int] | None = None) -> list[str]:
    """The journal, or one ordinal range of it, through imp's narrative renderer.
    quest_created leads every slice: it renders nothing but names the quest,
    without which a tail slice closes on a bare `Merged  into master.`"""
    selected = [e for e in events if e["ordinal"] != 1
                and (ordinals is None
                     or ordinals[0] <= e["ordinal"] <= ordinals[1])]
    return list(render_tree(nv.build_tree([events[0], *selected]),
                            color=False, width=WIDTH))


def excerpt_text(events: list[dict[str, Any]]) -> str:
    lines: list[str] = []
    previous = 0
    for first, last in EXCERPT_RANGES:
        if previous:
            lines += ["", _elision(first - previous - 1, "events"), ""]
        lines += narrative_lines(events, (first, last))
        previous = last
    return _fenced(f"imp log {QUEST}", lines)


def transcript_text(events: list[dict[str, Any]]) -> str:
    return (f"# {QUEST} — the complete run\n\n"
            f"Generated by `make docs-assets` from `docs/examples/{QUEST}.jsonl.gz`.\n"
            "Edits here are overwritten; change the generator instead.\n\n"
            + _fenced(f"imp log {QUEST}", narrative_lines(events)))
